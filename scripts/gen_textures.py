#!/usr/bin/env python3
"""Generate In-sight's original 16x16 pixel textures as CSS custom properties (data-URI SVGs).

Usage: python3 -I scripts/gen_textures.py > app/textures.css
"""
import base64, random, struct, zlib

def png(grid):
    """Encode a 16x16 colour grid as a tiny PNG data URI (stdlib only)."""
    raw = b"".join(b"\x00" + b"".join(bytes.fromhex(c[1:]) for c in row) for row in grid)
    def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 16, 16, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    return 'url("data:image/png;base64,' + base64.b64encode(data).decode() + '")'

def noise(pal, seed, weights=None):
    r = random.Random(seed)
    return [[r.choices(pal, weights)[0] for _ in range(16)] for _ in range(16)]

def planks(pal, seam, seed):
    g = noise(pal, seed, [5, 3, 2])
    for y in range(16):
        if y % 4 == 3: g[y] = [seam] * 16
    for band, x in enumerate([3, 11, 7, 14]):
        for y in range(band * 4, band * 4 + 3): g[y][x] = seam
    return g

def grass_side(seed):
    r = random.Random(seed)
    g = noise(["#866043", "#79553a", "#96704f", "#6b4a30"], seed + 1, [4, 3, 2, 1])
    greens = ["#5d9b3a", "#6aa84f", "#4f8a2f", "#7cbb5a"]
    for x in range(16):
        depth = r.choice([3, 3, 4, 4, 5])
        for y in range(depth): g[y][x] = r.choice(greens)
    return g

TEX = {
    "grass-side": grass_side(7),
    "grass-top": noise(["#5d9b3a", "#6aa84f", "#4f8a2f", "#7cbb5a"], 3, [4, 3, 2, 1]),
    "dirt": noise(["#866043", "#79553a", "#96704f", "#6b4a30"], 5, [4, 3, 2, 1]),
    "stone": noise(["#8a8a8a", "#7b7b7b", "#9a9a9a", "#6f6f6f"], 11, [5, 3, 2, 1]),
    "deepslate": noise(["#3c3c44", "#34343b", "#45454e", "#2d2d33"], 13, [5, 3, 2, 1]),
    "planks": planks(["#d7c185", "#cdb67a", "#e2cf96"], "#a8905a", 17),
    "planks-dark": planks(["#5a3d24", "#4e341e", "#664629"], "#33220f", 19),
    "parchment": noise(["#f4ead0", "#efe4c4", "#f7efd9", "#eadfbd"], 23, [6, 3, 3, 1]),
    "parchment-dark": noise(["#2a241f", "#262019", "#2e2822", "#221d17"], 29, [6, 3, 3, 1]),
    "emerald": noise(["#2fae4f", "#27a046", "#3cbf5c", "#1f8c3b"], 31, [5, 3, 2, 1]),
}
print("/* Generated by scripts/gen_textures.py — original 16x16 textures for the block theme. */")
print(":root{")
for k, g in TEX.items(): print(f"  --tx-{k}:{png(g)};")
print("}")
